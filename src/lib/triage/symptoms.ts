/**
 * Extracts symptom IDs from voice/text transcript.
 * Purely extracts symptom IDs; NEVER determines severity level.
 */
export function extractSymptomsLocally(transcript: string): string[] {
  if (!transcript || typeof transcript !== 'string') return [];
  const text = transcript.trim();
  const matched = new Set<string>();

  for (const item of SYMPTOM_KEYWORD_PATTERNS) {
    for (const pat of item.patterns) {
      if (pat.test(text)) {
        matched.add(item.id);
        break;
      }
    }
  }

  return Array.from(matched);
}
