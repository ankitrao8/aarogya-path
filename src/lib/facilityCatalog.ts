/**
 * Finds the closest recognized district center to a given coordinate
 */
export function findNearestDistrict(lat: number, lng: number): { district: string; distanceKm: number } {
  let minDistance = Infinity;
  let nearestDistrict = 'Gorakhpur';

  for (const [district, coords] of Object.entries(DISTRICT_COORDINATES)) {
    const d = calculateDistanceKm(lat, lng, coords.lat, coords.lng);
    if (d < minDistance) {
      minDistance = d;
      nearestDistrict = district;
    }
  }

  return { district: nearestDistrict, distanceKm: minDistance };
}

