import { getCurrentUser, logAudit } from '@/lib/auth';
import { prisma } from '@/lib/prisma';
import { evaluateTriage } from '@/lib/triage/engine';
import { TriageInput } from '@/lib/triage/types';
import { NextResponse } from 'next/server';

export async function POST(req: Request) {
  try {
    const body = await req.json();
    const currentUser = await getCurrentUser();

    const {
      patient,
      symptoms = [],
      answers = {},
      vitals,
      inputMethod = 'TAP',
      conductedByRole = currentUser?.role || 'PATIENT',
      conductedById = currentUser?.userId || null,
    } = body;

    const triageInput: TriageInput = {
      patient: {
        age: Number(patient?.age) || 30,
        sex: patient?.sex || 'MALE',
        isPregnant: Boolean(patient?.isPregnant),
        pregnancyWeeks: patient?.pregnancyWeeks ? Number(patient?.pregnancyWeeks) : undefined,
        knownConditions: Array.isArray(patient?.knownConditions) ? patient.knownConditions : [],
      },
      symptoms: Array.isArray(symptoms) ? symptoms : [],
      answers: typeof answers === 'object' && answers !== null ? answers : {},
      vitals,
    };

    const result = evaluateTriage(triageInput);

    // If user is authenticated and has a profile or profile is passed
    let assessmentRecord = null;
    let referralRecord = null;

    let targetProfileId = body.patientProfileId;
    if (!targetProfileId && currentUser) {
      const userProfile = await prisma.patientProfile.findUnique({
        where: { userId: currentUser.userId },
      });
      targetProfileId = userProfile?.id;
    }

    if (targetProfileId) {
      assessmentRecord = await prisma.assessment.create({
        data: {
          patientProfileId: targetProfileId,
          conductedByRole: String(conductedByRole),
          conductedById: conductedById,
          symptoms: JSON.stringify(triageInput.symptoms),
          answers: JSON.stringify(triageInput.answers),
          level: result.level,
          reasons: JSON.stringify(result.reasons),
          dangerSigns: JSON.stringify(result.dangerSigns),
          homeCareAdvice: result.homeCareAdvice.join('; '),
          recommendedFacility: result.recommendedFacility,
          ruleVersion: result.ruleVersion,
          inputMethod: String(inputMethod),
        },
      });

      // Automated Referral for ORANGE & RED cases
      if (result.level === 'RED' || result.level === 'ORANGE') {
        // Find suitable local ASHA and Doctor in same district if available
        const asha = await prisma.user.findFirst({
          where: { role: 'ASHA' },
        });
        const doctor = await prisma.user.findFirst({
          where: { role: 'DOCTOR' },
        });

        referralRecord = await prisma.referral.create({
          data: {
            assessmentId: assessmentRecord.id,
            patientProfileId: targetProfileId,
            assignedAshaId: asha?.id || null,
            assignedDoctorId: doctor?.id || null,
            level: result.level,
            status: 'NEW',
            clinicalNotes: `Automated referral generated by rule engine. Urgency: ${result.level}. Rule reasons: ${result.reasons[0] || 'N/A'}`,
            transportArranged: result.level === 'RED',
          },
        });

        // Notifications
        const alertPrefix = result.level === 'RED' ? '🚨 आपातकालीन RED' : '⚠️ आवश्यक ORANGE';
        if (asha) {
          await prisma.notification.create({
            data: {
              recipientRole: 'ASHA',
              recipientUserId: asha.id,
              title: `${alertPrefix} केस रेफरल`,
              message: `नया ट्रायज केस: ${result.level} - तुरंत मरीज से संपर्क करें।`,
              link: `/asha/referrals`,
              channel: 'IN_APP',
            },
          });
        }

        if (doctor) {
          await prisma.notification.create({
            data: {
              recipientRole: 'DOCTOR',
              recipientUserId: doctor.id,
              title: `${alertPrefix} क्लिनिकल रेफरल`,
              message: `मरीज ट्रायज स्तर: ${result.level}। समीक्षा हेतु केस विवरण देखें।`,
              link: `/doctor/referrals`,
              channel: 'IN_APP',
            },
          });
        }
      }

      // Schedule follow-up for YELLOW & ORANGE cases
      if (result.level === 'YELLOW' || result.level === 'ORANGE') {
        const delayHours = result.level === 'ORANGE' ? 8 : 24;
        await prisma.followUp.create({
          data: {
            assessmentId: assessmentRecord.id,
            scheduledFor: new Date(Date.now() + delayHours * 3600 * 1000),
            escalated: false,
          },
        });
      }

      await logAudit(
        'RUN_TRIAGE',
        'Assessment',
        assessmentRecord.id,
        currentUser?.userId || null
      );
    }

    return NextResponse.json({
      success: true,
      result,
      assessmentId: assessmentRecord?.id || null,
      referralId: referralRecord?.id || null,
    });
  } catch (error) {
    console.error('Error during triage assessment:', error);
    return NextResponse.json(
      { error: 'Triage assessment failed', details: String(error) },
      { status: 500 }
    );
  }
}
